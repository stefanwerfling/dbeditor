describe('PostgresDialect view renderers', () => {

    const d = new PostgresDialect();

    const view = (select: string, materialized = false): JsonView => ({
        unid: 'v',
        name: 'v_active',
        pos: {x: 0, y: 0},
        select: select,
        materialized: materialized
    });

    it('emits CREATE OR REPLACE VIEW for non-materialized', () => {
        const sql = d.renderCreateView(view('SELECT 1'), ctxFor([]));
        expect(sql).toBe('CREATE OR REPLACE VIEW "v_active" AS\nSELECT 1');
    });

    it('emits CREATE MATERIALIZED VIEW IF NOT EXISTS for materialized', () => {
        const sql = d.renderCreateView(view('SELECT 1', true), ctxFor([]));
        expect(sql).toBe('CREATE MATERIALIZED VIEW IF NOT EXISTS "v_active" AS\nSELECT 1');
    });

    it('renderReplaceView replaces non-materialized with CREATE OR REPLACE', () => {
        expect(d.renderReplaceView(view('SELECT 9'), ctxFor([])))
        .toBe('CREATE OR REPLACE VIEW "v_active" AS\nSELECT 9');
    });

    it('renderReplaceView drops-and-recreates materialized views', () => {
        const sql = d.renderReplaceView(view('SELECT 9', true), ctxFor([]));
        expect(sql).toContain('DROP MATERIALIZED VIEW IF EXISTS "v_active"');
        expect(sql).toContain('CREATE MATERIALIZED VIEW "v_active" AS\nSELECT 9');
    });

    it('DROP MATERIALIZED VIEW vs DROP VIEW based on flag', () => {
        expect(d.renderDropView(view('SELECT 1'), ctxFor([]))).toBe('DROP VIEW IF EXISTS "v_active"');
        expect(d.renderDropView(view('SELECT 1', true), ctxFor([]))).toBe('DROP MATERIALIZED VIEW IF EXISTS "v_active"');
    });

});

describe('PostgresDialect ALTER renderers (sync path)', () => {

    const d = new PostgresDialect();

    it('renders ADD COLUMN', () => {
        const t = table('users', [col('email', {type: 'varchar', length: '255', notNull: true})]);
        expect(d.renderAlterTableAddColumn(t, t.columns[0], ctxFor([t])))
        .toBe('ALTER TABLE "users" ADD COLUMN "email" VARCHAR(255) NOT NULL');
    });

    it('renders DROP COLUMN', () => {
        const t = table('users', [col('email')]);
        expect(d.renderAlterTableDropColumn(t, t.columns[0], ctxFor([t])))
        .toBe('ALTER TABLE "users" DROP COLUMN "email"');
    });

    it('emits SET DATA TYPE only when type/length differs', () => {
        const oldCol = col('email', {type: 'varchar', length: '64', notNull: true});
        const newCol = col('email', {type: 'varchar', length: '255', notNull: true});
        const t = table('users', [newCol]);
        const sql = d.renderAlterTableChangeColumn(t, oldCol, newCol, ctxFor([t]));
        expect(sql).toContain('SET DATA TYPE VARCHAR(255) USING "email"::VARCHAR(255)');
        expect(sql).not.toContain('DROP DEFAULT');
        expect(sql).not.toContain('NOT NULL');
    });

    it('emits SET DEFAULT when default value changes', () => {
        const oldCol = col('flag', {type: 'int'});
        const newCol = col('flag', {type: 'int', defaultValue: '0'});
        const t = table('t', [newCol]);
        const sql = d.renderAlterTableChangeColumn(t, oldCol, newCol, ctxFor([t]));
        expect(sql).toBe('ALTER TABLE "t" ALTER COLUMN "flag" SET DEFAULT 0');
    });

    it('emits DROP DEFAULT when old had default and new does not', () => {
        const oldCol = col('flag', {type: 'int', defaultValue: '0'});
        const newCol = col('flag', {type: 'int'});
        const t = table('t', [newCol]);
        const sql = d.renderAlterTableChangeColumn(t, oldCol, newCol, ctxFor([t]));
        expect(sql).toBe('ALTER TABLE "t" ALTER COLUMN "flag" DROP DEFAULT');
    });

    it('emits SET NOT NULL / DROP NOT NULL on nullability flip', () => {
        const t = table('t', [col('x')]);
        const setNN = d.renderAlterTableChangeColumn(t, col('x', {notNull: false}), col('x', {notNull: true}), ctxFor([t]));
        expect(setNN).toBe('ALTER TABLE "t" ALTER COLUMN "x" SET NOT NULL');
        const dropNN = d.renderAlterTableChangeColumn(t, col('x', {notNull: true}), col('x', {notNull: false}), ctxFor([t]));
        expect(dropNN).toBe('ALTER TABLE "t" ALTER COLUMN "x" DROP NOT NULL');
    });

    it('combines multiple actions in one ALTER TABLE', () => {
        const oldCol = col('x', {type: 'varchar', length: '64', notNull: false});
        const newCol = col('x', {type: 'varchar', length: '255', notNull: true, defaultValue: '\'foo\''});
        const t = table('t', [newCol]);
        const sql = d.renderAlterTableChangeColumn(t, oldCol, newCol, ctxFor([t]));
        expect(sql).toContain('SET DATA TYPE VARCHAR(255)');
        expect(sql).toContain('SET DEFAULT \'foo\'');
        expect(sql).toContain('SET NOT NULL');
        /* one statement, comma-separated actions */
        expect(sql.match(/ALTER TABLE/gu)?.length).toBe(1);
    });

    it('renders DROP CONSTRAINT (not DROP FOREIGN KEY) for the FK drop path', () => {
        const t = table('orders', [col('user_id')]);
        expect(d.renderDropForeignKey(t, 'fk_user', ctxFor([t])))
        .toBe('ALTER TABLE "orders" DROP CONSTRAINT "fk_user"');
    });

    it('renderAlterTableOptions returns null when no postgres-relevant option set', () => {
        const t = table('t', [col('id')], {options: {engine: 'InnoDB', charset: 'utf8'}});
        expect(d.renderAlterTableOptions(t, ctxFor([t]))).toBeNull();
    });

    it('renderAlterTableOptions emits SET TABLESPACE / SET UNLOGGED', () => {
        const t = table('t', [col('id')], {options: {tablespace: 'fast', persistence: 'UNLOGGED'}});
        expect(d.renderAlterTableOptions(t, ctxFor([t])))
        .toBe('ALTER TABLE "t" SET TABLESPACE "fast", SET UNLOGGED');
    });

    it('renderAlterTableOptions chains COMMENT ON TABLE as a separate statement', () => {
        const t = table('t', [col('id')], {options: {comment: 'core'}});
        const sql = d.renderAlterTableOptions(t, ctxFor([t]));
        expect(sql).toBe('COMMENT ON TABLE "t" IS \'core\'');

        const both = table('t', [col('id')], {options: {tablespace: 'fast', comment: 'core'}});
        const chained = d.renderAlterTableOptions(both, ctxFor([both]));
        expect(chained).toBe('ALTER TABLE "t" SET TABLESPACE "fast"; COMMENT ON TABLE "t" IS \'core\'');
    });

});